/**
 * Bundle the browser NEMSIS code (schema, validation, XML export, ePCR model) into one CommonJS file Cloud
 * Functions can require, so the server builds and checks a report exactly the way the app does.
 *
 *   npm run bundle:nemsis-functions
 *
 * Output: functions/lib/nemsis/generated/nemsisCore.cjs, with a header holding a hash of every source file.
 * tests/unit/nemsisFunctionsBundle.test.mjs fails when the sources change and the bundle wasn't rebuilt.
 * Re-run after changing anything in src/lib/nemsis/ or src/data/nemsis/.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import { nemsisBundleSourceHash, ROOT, ENTRY, OUT_FILE } from "./nemsisBundleSources.mjs";

async function main() {
  const result = await build({
    configFile: false,
    logLevel: "warn",
    root: ROOT,
    build: {
      write: false,
      minify: false,
      sourcemap: false,
      emptyOutDir: false,
      lib: { entry: ENTRY, formats: ["cjs"], fileName: () => "nemsisCore.cjs" },
      rollupOptions: { output: { exports: "named" } },
    },
  });
  const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => r.output);
  const chunk = outputs.find((o) => o.type === "chunk" && o.isEntry);
  if (!chunk) throw new Error("bundle-nemsis-functions: no output");
  const hash = await nemsisBundleSourceHash();
  const header =
    "// GENERATED by scripts/nemsis/bundle-nemsis-functions.mjs from src/lib/nemsis and src/data/nemsis. Do not edit.\n" +
    `// source-hash: ${hash}\n`;
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
  await fs.writeFile(OUT_FILE, header + chunk.code);
  const size = Buffer.byteLength(chunk.code);
  console.log(`${path.relative(ROOT, OUT_FILE)} (${Math.round(size / 1024)} KB, source-hash ${hash.slice(0, 12)})`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err?.message ?? err);
    process.exit(1);
  });
}
