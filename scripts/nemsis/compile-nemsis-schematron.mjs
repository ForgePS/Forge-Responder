/**
 * Compile the NEMSIS national Schematron into SaxonJS stylesheets the server can run.
 *
 *   node scripts/nemsis/compile-nemsis-schematron.mjs              # 3.5.1
 *   node scripts/nemsis/compile-nemsis-schematron.mjs --version 3.5.1
 *
 * Input:  functions/nemsis/<version>/schematron/{EMSDataSet,DEMDataSet}.sch.xml (from sync-nemsis-schema.mjs)
 * Output: functions/nemsis/<version>/schematron/compiled/<dataset>.sef.json.gz
 *
 * Same pipeline as the NEMSIS kit's CompileSchematron.bat (the .sch.xml files already have includes expanded):
 *   1. iso_abstract_expand.xsl   .sch.xml → expanded .sch
 *   2. iso_svrl_for_xslt2.xsl    expanded .sch → XSLT that emits SVRL   (allow-foreign=true, for nemsisDiagnostic)
 *   3. xslt3 -export             XSLT → SaxonJS SEF, gzipped (about 6 MB → well under 1 MB)
 * Takes about a minute. Re-run after every sync of a new NEMSIS version or critical patch.
 */
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import zlib from "node:zlib";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..", "..");
const args = process.argv.slice(2);
const VERSION = args.includes("--version") ? args[args.indexOf("--version") + 1] : "3.5.1";
const ISO_DIR = path.join(ROOT, "functions", "nemsis", "iso-schematron-xslt2");
const SCH_DIR = path.join(ROOT, "functions", "nemsis", VERSION, "schematron");
const OUT_DIR = path.join(SCH_DIR, "compiled");
const XSLT3 = path.join(ROOT, "node_modules", "xslt3", "xslt3.js");
const DATASETS = ["EMSDataSet", "DEMDataSet"];

function xslt3(cliArgs) {
  const res = spawnSync(process.execPath, [XSLT3, ...cliArgs], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (res.status !== 0) {
    throw new Error(`xslt3 ${cliArgs.join(" ")}\n${res.stdout}\n${res.stderr}`);
  }
  return res;
}

async function main() {
  await fs.access(XSLT3).catch(() => {
    throw new Error("xslt3 is not installed; run npm install");
  });
  const tmp = await fs.mkdtemp(path.join(os.tmpdir(), "nemsis-sch-"));
  await fs.mkdir(OUT_DIR, { recursive: true });
  try {
    for (const ds of DATASETS) {
      const source = path.join(SCH_DIR, `${ds}.sch.xml`);
      const expanded = path.join(tmp, `${ds}.sch`);
      const xsl = path.join(tmp, `${ds}.xsl`);
      const sef = path.join(tmp, `${ds}.sef.json`);
      const started = Date.now();
      xslt3([`-xsl:${path.join(ISO_DIR, "iso_abstract_expand.xsl")}`, `-s:${source}`, `-o:${expanded}`]);
      xslt3([`-xsl:${path.join(ISO_DIR, "iso_svrl_for_xslt2.xsl")}`, `-s:${expanded}`, `-o:${xsl}`, "allow-foreign=true"]);
      xslt3([`-xsl:${xsl}`, `-export:${sef}`, "-nogo", "-relocate:on"]);

      const sefText = await fs.readFile(sef);
      const schemaVersion = /schemaVersion="([^"]+)"/.exec(await fs.readFile(source, "utf8"))?.[1] ?? "unknown";
      const out = path.join(OUT_DIR, `${ds}.sef.json.gz`);
      await fs.writeFile(out, zlib.gzipSync(sefText, { level: 9 }));
      const stat = await fs.stat(out);
      console.log(`${ds} ${schemaVersion}: ${path.relative(ROOT, out)} (${Math.round(stat.size / 1024)} KB, ${Math.round((Date.now() - started) / 1000)} s)`);
    }
    await fs.writeFile(
      path.join(OUT_DIR, "README.md"),
      "Generated by `scripts/nemsis/compile-nemsis-schematron.mjs` from the national Schematron in `..`.\n" +
        "Do not edit. Loaded by `functions/lib/nemsis/schematron.js`.\n",
    );
  } finally {
    await fs.rm(tmp, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err.message ?? err);
  process.exit(1);
});
