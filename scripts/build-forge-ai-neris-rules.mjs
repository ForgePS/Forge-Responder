/**
 * Bundle Forge's NERIS validation rules (src/lib/neris/validation.js, ESM with
 * JSON imports) into CommonJS so Cloud Functions can run the exact same rules.
 *
 *   npm run build:forge-ai
 *
 * Output: functions/lib/forgeAi/generated/nerisValidation.cjs (committed), or
 * the path given as the first argument (the drift test builds to a temp file).
 * tests/unit/forgeAi.test.mjs fails if the committed bundle drifts from src/.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = process.argv[2] ? resolve(process.argv[2]) : join(ROOT, "functions", "lib", "forgeAi", "generated", "nerisValidation.cjs");

mkdirSync(dirname(OUT), { recursive: true });
execFileSync(process.execPath, [
  join(ROOT, "node_modules", "rolldown", "bin", "cli.mjs"),
  "src/lib/neris/validation.js",
  "--format", "cjs",
  "--platform", "node",
  "-o", OUT,
], { cwd: ROOT, stdio: process.argv[2] ? "pipe" : "inherit" });

const body = readFileSync(OUT, "utf8");
writeFileSync(OUT, `// GENERATED by scripts/build-forge-ai-neris-rules.mjs from src/lib/neris/validation.js. Do not edit.\n${body}`);
console.log(`Wrote ${OUT}`);
