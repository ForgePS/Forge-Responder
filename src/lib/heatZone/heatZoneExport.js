/**
 * Heat Zone report exports. The report payload comes from the heatZoneReport
 * callable, which has already applied the caller's tenant, district and
 * export permissions; these helpers only format it.
 */
import * as XLSX from "xlsx";
import { downloadTextFile } from "../downloadTextFile.js";

function csvCell(value) {
  const text = value === null || value === undefined ? "" : String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/** Header block every export carries: agency, range, filters, generation time. */
export function reportHeaderRows(meta) {
  return [
    [meta.title],
    ["Agency", `${meta.agencyName} (${meta.departmentId})`],
    ["Date range", `${meta.from} to ${meta.to} (${meta.timeZone})`],
    ["Filters", (meta.filters || []).join("; ")],
    ["District scope", meta.districtScope],
    ["Calls in report", meta.totalCalls],
    ["Generated", `${meta.generatedAtLocal} · ${new Date(meta.generatedAt).toISOString()} UTC`],
    ["Generated by", meta.generatedBy],
    ...(meta.truncated ? [["Note", "Result limited to the first 50,000 incidents in range."]] : []),
    [],
  ];
}

export function reportToCsv(report) {
  const rows = [...reportHeaderRows(report.meta), report.columns, ...report.rows, [], ...(report.notes || []).map((n) => ["Note", n])];
  return rows.map((row) => row.map(csvCell).join(",")).join("\r\n");
}

export function reportFilename(meta, ext) {
  const safe = (v) => String(v || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return `heat-zone-${safe(meta.reportType)}-${safe(meta.departmentId)}-${meta.from}-to-${meta.to}.${ext}`;
}

export function downloadReportCsv(report) {
  downloadTextFile(reportFilename(report.meta, "csv"), reportToCsv(report));
}

export function downloadReportXlsx(report) {
  const sheet = XLSX.utils.aoa_to_sheet([...reportHeaderRows(report.meta), report.columns, ...report.rows]);
  sheet["!cols"] = report.columns.map((_, i) => ({ wch: i === 0 ? 34 : 18 }));
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, sheet, "Report");
  if (report.notes?.length) XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(report.notes.map((n) => [n])), "Notes");
  XLSX.writeFile(book, reportFilename(report.meta, "xlsx"));
}

const escapeHtml = (v) => String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

/** Printable report (browser "Save as PDF"), same pattern as the hydrant print reports. */
export function openReportPrint(report) {
  const { meta } = report;
  const header = reportHeaderRows(meta).filter((r) => r.length === 2)
    .map(([k, v]) => `<tr><th>${escapeHtml(k)}</th><td>${escapeHtml(v)}</td></tr>`).join("");
  const body = report.rows.map((row) => `<tr>${row.map((c) => `<td>${escapeHtml(c)}</td>`).join("")}</tr>`).join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(meta.title)} — ${escapeHtml(meta.agencyName)}</title>
<style>body{font:12px/1.4 system-ui,sans-serif;color:#111;margin:24px}h1{font-size:18px;margin:0 0 8px}table{border-collapse:collapse;width:100%;margin:12px 0}
th,td{border:1px solid #ccc;padding:4px 6px;text-align:left}thead th{background:#f1f5f9}.meta th{width:160px;background:#f8fafc}p{color:#555}@media print{button{display:none}}</style></head>
<body><h1>${escapeHtml(meta.title)}</h1><table class="meta">${header}</table>
<table><thead><tr>${report.columns.map((c) => `<th>${escapeHtml(c)}</th>`).join("")}</tr></thead><tbody>${body}</tbody></table>
${(report.notes || []).map((n) => `<p>${escapeHtml(n)}</p>`).join("")}
<p>Forge Responder · Heat Zone Analytics · Confidential — ${escapeHtml(meta.agencyName)}</p>
<script>window.addEventListener("load",()=>setTimeout(()=>window.print(),250));</script></body></html>`;
  const url = URL.createObjectURL(new Blob([html], { type: "text/html" }));
  const popup = window.open(url, "_blank", "noopener=no,width=1000,height=800");
  window.setTimeout(() => URL.revokeObjectURL(url), 60000);
  if (!popup) throw new Error("Pop-up blocked. Allow pop-ups for this site to print or save the report as PDF.");
}
