export function isPersonnelCollection(collectionName = "") {
  return collectionName === "hlfd-rms-personnel";
}

export function personnelAdminLabel(column = "") {
  return PERSONNEL_ADMIN_FIELD_LABELS[column] || null;
}

export function orderPersonnelColumns(columns = []) {
  const unique = Array.from(new Set(columns));
  return [
    ...PERSONNEL_ADMIN_COLUMN_ORDER.filter((column) => unique.includes(column)),
    ...unique.filter((column) => !PERSONNEL_ADMIN_COLUMN_ORDER.includes(column)),
  ];
}
