/** Seed dropdown libraries for Pre-Fire Plan Configuration Studio (Phase 2). */

function opts(...labels) {
  return labels.map((label, index) => ({
    id: String(label)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .replace(/^_|_$/g, "")
      .slice(0, 48) || `opt_${index}`,
    label,
  }));
}

